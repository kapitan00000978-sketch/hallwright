"""
Blender to After Effects Camera & Null Exporter
Executes inside Blender (via bpy) to export Active Camera & Selected Objects
as an Adobe After Effects ExtendScript (.jsx) file.
"""

import bpy
import math
import os
import sys
from mathutils import Matrix, Vector

def get_ae_camera_data(cam_obj, scene):
    """Convert Blender camera coordinates to After Effects camera coordinates."""
    render = scene.render
    width = render.resolution_x
    height = render.resolution_y
    aspect = width / height
    
    start_frame = scene.frame_start
    end_frame = scene.frame_end
    fps = scene.render.fps / scene.render.fps_base

    cam_data = cam_obj.data
    sensor_width = cam_data.sensor_width
    
    keyframes = []

    for f in range(start_frame, end_frame + 1):
        scene.frame_set(f)
        matrix = cam_obj.matrix_world
        loc, rot, _ = matrix.decompose()
        
        # In Blender: X right, Y forward, Z up
        # In AE: X right, Y down, Z forward
        # AE coordinate conversion factor (pixels per meter)
        scale_factor = 100.0 # Standard conversion
        ae_x = (loc.x * scale_factor) + (width / 2.0)
        ae_y = (-loc.z * scale_factor) + (height / 2.0)
        ae_z = -loc.y * scale_factor

        # Focal length conversion
        focal_length_mm = cam_data.focal_length
        focal_pixels = (focal_length_mm / sensor_width) * width

        # Rotation conversions (Euler in degrees)
        rot_euler = matrix.to_euler('ZYX')
        rx = math.degrees(rot_euler.x) - 90
        ry = -math.degrees(rot_euler.z)
        rz = math.degrees(rot_euler.y)

        keyframes.append({
            "frame": f - start_frame,
            "time": (f - start_frame) / fps,
            "pos": [ae_x, ae_y, ae_z],
            "rot": [rx, ry, rz],
            "zoom": focal_pixels
        })

    return {
        "name": cam_obj.name,
        "width": width,
        "height": height,
        "fps": fps,
        "duration": (end_frame - start_frame + 1) / fps,
        "keyframes": keyframes
    }

def generate_jsx(cam_info, output_jsx_path, extra_nulls=None):
    """Generate After Effects JSX script that creates Comp, Camera, and Nulls."""
    jsx = []
    jsx.append("// Auto-generated by Blender-to-AE Bridge")
    jsx.append("app.beginUndoGroup('Import Blender 3D Data');\n")
    
    # Create or fetch Comp
    comp_name = "Blender_VFX_Comp"
    w = cam_info["width"]
    h = cam_info["height"]
    fps = cam_info["fps"]
    dur = cam_info["duration"]
    
    jsx.append(f'var comp = app.project.items.addComp("{comp_name}", {w}, {h}, 1.0, {dur}, {fps});')
    jsx.append('comp.openInViewer();\n')
    
    # Create Camera
    cam_name = cam_info["name"]
    jsx.append(f'var camera = comp.layers.addCamera("{cam_name}", [{w}/2, {h}/2]);')
    jsx.append('camera.autoOrient = AutoOrientType.NO_AUTO_ORIENT;')
    jsx.append('var posProp = camera.property("Position");')
    jsx.append('var zoomProp = camera.property("Camera Options").property("Zoom");')
    jsx.append('var rotX = camera.property("X Rotation");')
    jsx.append('var rotY = camera.property("Y Rotation");')
    jsx.append('var rotZ = camera.property("Z Rotation");\n')

    # Apply Keyframes
    for kf in cam_info["keyframes"]:
        t = kf["time"]
        pos = kf["pos"]
        rot = kf["rot"]
        zoom = kf["zoom"]
        jsx.append(f'posProp.setValueAtTime({t:.4f}, [{pos[0]:.2f}, {pos[1]:.2f}, {pos[2]:.2f}]);')
        jsx.append(f'zoomProp.setValueAtTime({t:.4f}, {zoom:.2f});')
        jsx.append(f'rotX.setValueAtTime({t:.4f}, {rot[0]:.2f});')
        jsx.append(f'rotY.setValueAtTime({t:.4f}, {rot[1]:.2f});')
        jsx.append(f'rotZ.setValueAtTime({t:.4f}, {rot[2]:.2f});')

    # Optional extra 3D nulls
    if extra_nulls:
        for null_name, loc in extra_nulls.items():
            ae_x = (loc[0] * 100.0) + (w / 2.0)
            ae_y = (-loc[2] * 100.0) + (h / 2.0)
            ae_z = -loc[1] * 100.0
            jsx.append(f'\nvar nullLayer = comp.layers.addNull();')
            jsx.append(f'nullLayer.name = "{null_name}";')
            jsx.append('nullLayer.threeDLayer = true;')
            jsx.append(f'nullLayer.property("Position").setValue([{ae_x:.2f}, {ae_y:.2f}, {ae_z:.2f}]);')

    jsx.append("\napp.endUndoGroup();")
    jsx.append(f'alert("Successfully imported Blender Camera: {cam_name} into Comp: {comp_name}!");')

    content = "\n".join(jsx)
    with open(output_jsx_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"[SUCCESS] Exported AE JSX script to: {output_jsx_path}")

def run_export(output_jsx="blender_camera_to_ae.jsx"):
    scene = bpy.context.scene
    cam = scene.camera
    if not cam:
        print("[ERROR] No active camera in Blender scene.")
        return False
        
    cam_data = get_ae_camera_data(cam, scene)
    
    # Collect selected objects as 3D Null references
    extra_nulls = {}
    for obj in bpy.context.selected_objects:
        if obj != cam:
            extra_nulls[obj.name] = obj.location
            
    generate_jsx(cam_data, output_jsx, extra_nulls)
    return True

if __name__ == "__main__":
    out = "blender_to_ae.jsx"
    if "--" in sys.argv:
        args = sys.argv[sys.argv.index("--") + 1:]
        if args:
            out = args[0]
    run_export(out)
