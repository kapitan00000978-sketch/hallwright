"""
Hallwright Titan AgentMesh: Zero-Dependency Asynchronous Sub-Agent Communications Mesh.
Part of Pillar III: Sub-Agent Mesh & Autonomous Intelligence Architecture.

Provides:
- Typed event bus with decoupled publisher/subscriber channels
- Cross-agent collaboration with trace_id correlation
- Deadlock-free asynchronous and synchronous dispatch
- Invariant-governed agent contracts
"""

import os
import sys
import json
import time
import uuid
import logging
import threading
from typing import Dict, List, Any, Optional, Callable, Set
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone

logger = logging.getLogger("hallwright.mesh")


@dataclass
class AgentMessage:
    """Canonical message envelope passed between autonomous agents across the mesh."""
    topic: str
    sender: str
    payload: Dict[str, Any]
    trace_id: str = field(default_factory=lambda: f"tr_{uuid.uuid4().hex[:12]}")
    message_id: str = field(default_factory=lambda: f"msg_{uuid.uuid4().hex[:8]}")
    parent_id: Optional[str] = None
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "AgentMessage":
        return cls(
            topic=data.get("topic", "general"),
            sender=data.get("sender", "anonymous"),
            payload=data.get("payload", {}),
            trace_id=data.get("trace_id", f"tr_{uuid.uuid4().hex[:12]}"),
            message_id=data.get("message_id", f"msg_{uuid.uuid4().hex[:8]}"),
            parent_id=data.get("parent_id"),
            timestamp=data.get("timestamp", datetime.now(timezone.utc).isoformat())
        )


@dataclass
class AgentContract:
    """Formal interface agreement defining what an agent accepts and guarantees."""
    agent_id: str
    role: str
    subscribed_topics: List[str]
    published_topics: List[str]
    max_concurrency: int = 4
    timeout_seconds: float = 30.0


class AgentMesh:
    """
    Decoupled, zero-dependency event bus and coordination mesh for Hallwright sub-agents.
    Thread-safe and supports both synchronous batch pipelines and live event-driven workflows.
    """

    def __init__(self, workspace_root: str = "."):
        self.workspace_root = workspace_root
        self._subscribers: Dict[str, List[Callable[[AgentMessage], Optional[AgentMessage]]]] = {}
        self._contracts: Dict[str, AgentContract] = {}
        self._message_history: List[AgentMessage] = []
        self._max_history = 1000
        self._lock = threading.RLock()
        self._ledger_path = os.path.join(workspace_root, ".hallwright", "mesh_ledger.json")

    def register_agent(self, contract: AgentContract) -> None:
        """Registers an agent's contractual agreement with the mesh."""
        with self._lock:
            self._contracts[contract.agent_id] = contract
            for topic in contract.subscribed_topics:
                if topic not in self._subscribers:
                    self._subscribers[topic] = []

    def subscribe(self, topic: str, handler: Callable[[AgentMessage], Optional[AgentMessage]]) -> None:
        """Subscribes a callable handler to a specific mesh topic."""
        with self._lock:
            if topic not in self._subscribers:
                self._subscribers[topic] = []
            if handler not in self._subscribers[topic]:
                self._subscribers[topic].append(handler)

    def publish(self, message: AgentMessage) -> List[AgentMessage]:
        """
        Publishes a message to all subscribers of message.topic.
        Returns any response messages generated by subscribers.
        """
        responses: List[AgentMessage] = []
        with self._lock:
            self._message_history.append(message)
            if len(self._message_history) > self._max_history:
                self._message_history.pop(0)

            handlers = list(self._subscribers.get(message.topic, []))
            # Also notify wildcard subscribers if any
            if "*" in self._subscribers:
                handlers.extend(self._subscribers["*"])

        for handler in handlers:
            try:
                res = handler(message)
                if isinstance(res, AgentMessage):
                    res.parent_id = message.message_id
                    res.trace_id = message.trace_id
                    responses.append(res)
            except Exception as exc:
                logger.error("Mesh handler error on topic '%s': %s", message.topic, exc)

        return responses

    def dispatch(
        self,
        topic: str,
        sender: str,
        payload: Dict[str, Any],
        trace_id: Optional[str] = None
    ) -> List[AgentMessage]:
        """Convenience method to construct and publish an AgentMessage."""
        msg = AgentMessage(
            topic=topic,
            sender=sender,
            payload=payload,
            trace_id=trace_id or f"tr_{uuid.uuid4().hex[:12]}"
        )
        return self.publish(msg)

    def get_history(self, trace_id: Optional[str] = None, limit: int = 50) -> List[Dict[str, Any]]:
        """Retrieves past messages filtered by trace_id or chronological tail."""
        with self._lock:
            if trace_id:
                filtered = [m.to_dict() for m in self._message_history if m.trace_id == trace_id]
            else:
                filtered = [m.to_dict() for m in self._message_history]
            return filtered[-limit:]

    def export_ledger(self) -> str:
        """Dumps current in-memory message history to .hallwright/mesh_ledger.json."""
        with self._lock:
            os.makedirs(os.path.dirname(self._ledger_path), exist_ok=True)
            data = {
                "version": "1.0.0",
                "exported_at": datetime.now(timezone.utc).isoformat(),
                "total_messages": len(self._message_history),
                "active_agents": list(self._contracts.keys()),
                "history": [m.to_dict() for m in self._message_history]
            }
            with open(self._ledger_path, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2)
            return self._ledger_path


# Global mesh instance
_GLOBAL_MESH: Optional[AgentMesh] = None

def get_agent_mesh(workspace_root: str = ".") -> AgentMesh:
    """Returns the shared singleton AgentMesh instance for the workspace."""
    global _GLOBAL_MESH
    if _GLOBAL_MESH is None:
        _GLOBAL_MESH = AgentMesh(workspace_root=workspace_root)
    return _GLOBAL_MESH
